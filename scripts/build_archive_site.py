"""Publish the original competition UI with verified archived media, no AWS.

Usage: python3 scripts/build_archive_site.py --output /tmp/agent-nba-site
Only the generated output is replaced. Source web/ and portfolio/ are preserved.
"""
import argparse
import copy
import hashlib
import json
from pathlib import Path
import shutil

ROOT = Path(__file__).resolve().parents[1]


def archive_pack():
    web = ROOT / "web"
    code = (web / "replay/clips.js").read_text()
    prefix = "window.DEEPCOURT_CLIPS="
    assert code.startswith(prefix), "Unexpected replay manifest format"
    original = json.loads(code[len(prefix):].strip().removesuffix(";"))["flagg"]
    media = json.loads((web / "replay/archive-media.json").read_text())
    file = web / media["file"]
    assert hashlib.sha256(file.read_bytes()).hexdigest() == media["sha256"], "Archived video changed; recheck timeline before publishing"
    pack = copy.deepcopy(original)
    shot = pack["shots"][0]
    release = shot["release"]["t"]
    before = next(row for row in reversed(pack["scorebug"]) if row["t"] <= release + .05)
    after = next(row for row in pack["scorebug"] if row["t"] > release and row["awayScore"] + row["homeScore"] > before["awayScore"] + before["homeScore"])
    # Match the insertion algorithm in pipeline/present/freeze.py, not a
    # guessed linear rescale between original and rendered video durations.
    goal = min(after["t"] + .3, pack["duration"] - .4)
    freeze = media["freezeSeconds"]
    for event in pack["events"]:
        event["originalTime"] = event["t"]
        if event["t"] >= goal:
            event["t"] += freeze
    pack["events"].extend([
        {"t": goal + .05, "label": "出手定格回看 · 弗拉格 #32", "detail": "成片中已烧录的回放定格，不是网页再次生成的识别结果。", "source": "rendered_replay", "shot": shot},
        {"t": goal + freeze, "label": "恢复比赛回放", "detail": "成片结束定格，继续原比赛画面。", "source": "rendered_replay"},
    ])
    pack["events"].sort(key=lambda row: row["t"])
    for event in pack["events"]:
        seconds = int(event["t"])
        event["timecode"] = f"{seconds // 60:02}:{seconds % 60:02}"
        assert 0 <= event["t"] < media["duration"]
    pack.update(video=media["file"], replayVideo=media["file"], duration=media["duration"], anchor=0,
                preRenderedFreeze=True, title="弗拉格对火箭 · 原比赛回放成片",
                voice="原项目保存的成片与自带音轨。当前使用离线分析快照；不进行实时识别或云端问答。",
                archiveFreeze={"start": goal, "end": goal + freeze, "release": release})
    for key in ["tracks", "scriptEn", "scriptZh", "sourceVideo"]:
        pack.pop(key, None)
    return pack


def build(output):
    output = output.resolve()
    # Refuse arbitrary deletion or overlap with either checkout/source tree.
    if output == ROOT or ROOT in output.parents or output in ROOT.parents or output == Path("/"):
        raise ValueError("Output must be a dedicated directory outside the checkout")
    if output.exists():
        marker = output / ".agent-nba-generated"
        if not marker.is_file():
            raise ValueError("Refusing to overwrite a directory not generated by this script")
        shutil.rmtree(output)
    pack = archive_pack()
    output.mkdir(parents=True)
    (output / ".agent-nba-generated").touch()
    (output / ".nojekyll").touch()
    web = ROOT / "web"
    for name in ["game.html", "styles.css", "game.js", "replay-freeze.js", "analyst.js", "archive.js", "archive.css", "arch.html", "official-clips.html", "official-clips.css", "official-clips.js"]:
        shutil.copy2(web / name, output / name)
    shutil.copy2(web / "game.html", output / "index.html")
    for name in ["fonts", "logos", "headshots", "schedules", "brands"]:
        shutil.copytree(web / name, output / name)
    (output / "assets").mkdir()
    shutil.copy2(web / pack["video"], output / pack["video"])
    (output / "replay").mkdir()
    for name in ["official-clips.json", "official-clips-validation.json"]:
        shutil.copy2(web / "replay" / name, output / "replay" / name)
    (output / "replay/clips.js").write_text("window.DEEPCOURT_CLIPS=" + json.dumps({"flagg": pack}, ensure_ascii=False) + ";\nwindow.DEEPCOURT_LEAD='flagg';\n")
    config = {"offline": True, "examOnly": False, "webNames": False, "hiddenTracks": [], "sampleClips": [], "githubUrl": "https://github.com/Max-lzp/Agent-NBA", "analystPresets": []}
    (output / "config.js").write_text("window.DEEPCOURT_CONFIG=" + json.dumps(config, ensure_ascii=False) + ";\n")
    readme = (web / "readme.html").read_text().replace('href="/game.html"', 'href="game.html"')
    banner = '<aside style="margin:64px auto 20px;max-width:760px;padding:16px;border:1px solid #f1681e;color:#f3ede2">这是比赛时的作品说明归档；文中的 CloudFront、AWS 和部署状态不代表当前服务。<a href="game.html">返回当前离线回放</a> · <a href="case-study/index.html">查看作品集说明</a></aside>'
    readme = readme.replace("<body>", "<body>" + banner, 1)
    (output / "readme.html").write_text(readme)
    shutil.copytree(ROOT / "portfolio", output / "case-study")
    # Keep the previous tool URL working without leaving it as the home page.
    (output / "player.html").write_text('<!doctype html><meta charset="utf-8"><meta http-equiv="refresh" content="0;url=case-study/player.html"><title>本地标记工具</title><a href="case-study/player.html">打开本地标记工具</a>')
    print(f"Original competition replay site built: {output}")
    return output


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path, required=True)
    build(parser.parse_args().output)
